let _lang = DEFAULT_LANG;
let _listeners = [];

function _loadLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved && STRINGS[saved]) return saved;
  } catch (e) { /* 忽略存储异常 */ }
  return DEFAULT_LANG;
}

/** 取当前语言下的翻译；支持 {变量} 替换 */
export function t(key, vars) {
  const table = STRINGS[_lang] || STRINGS[DEFAULT_LANG];
  let s = table[key] ?? STRINGS[DEFAULT_LANG][key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}

export function getLang() { return _lang; }

/** 切换语言并立即应用界面翻译 */
export function setLang(lang) {
  if (!STRINGS[lang]) return;
  _lang = lang;
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch (e) { /* 忽略存储异常 */ }
  applyTranslations();
  _listeners.forEach(fn => fn(lang));
}

/** 注册语言变更回调（如重建原生菜单、刷新历史列表） */
export function onLangChange(fn) {
  _listeners.push(fn);
}

/** 应用翻译到整个 DOM */
export function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.getAttribute('data-i18n-title'));
  });
  document.querySelectorAll('[data-i18n-help]').forEach(el => {
    el.setAttribute('data-help', t(el.getAttribute('data-i18n-help')));
  });

  const tpl = document.getElementById('helpFormat');
  if (tpl) {
    tpl.content.querySelectorAll('[data-i18n]').forEach(el => {
      el.textContent = t(el.getAttribute('data-i18n'));
    });
  }

  document.documentElement.lang = _lang;
  document.querySelectorAll('#langPanel .lang-item').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === _lang);
  });
}

/** 初始化：读取保存的语言并应用 */
export function initI18n() {
  _lang = _loadLang();
  document.documentElement.lang = _lang;
  applyTranslations();
}

/** 初始化右上角语言切换菜单 */
export function initLanguageMenu() {
  const btn = document.getElementById('langBtn');
  const panel = document.getElementById('langPanel');
  if (!btn || !panel) return;

  btn.addEventListener('click', e => {
    e.stopPropagation();
    panel.hidden = !panel.hidden;
  });

  panel.addEventListener('click', e => {
    const item = e.target.closest('.lang-item');
    if (!item) return;
    setLang(item.dataset.lang);
    panel.hidden = true;
  });

  document.addEventListener('click', e => {
    if (!panel.hidden && !panel.contains(e.target) && e.target !== btn) {
      panel.hidden = true;
    }
  });

  document.addEventListener('keydown', e => {
    if (e.key === 'Escape') panel.hidden = true;
  });
}
